import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const migrationsDirectory = join(process.cwd(), "src", "server", "db", "migrations");
const outputPath = join(process.cwd(), "src", "server", "db", "initial-v1.sql");

function removeMigrationBookkeeping(sql) {
  return sql
    .replace(/^\uFEFF/, "")
    .replace(/^\s*(BEGIN TRANSACTION|COMMIT);?\s*$/gim, "")
    .replace(/INSERT\s+(?:OR\s+IGNORE\s+)?INTO\s+schema_migrations\s*\([\s\S]*?;\s*/gi, "")
    .trim();
}

const fileNames = (await readdir(migrationsDirectory))
  .filter((fileName) => /^\d{3}_.*\.sql$/.test(fileName))
  .sort();
const chunks = [];
const versions = [];

for (const fileName of fileNames) {
  const version = Number(fileName.slice(0, 3));
  const name = fileName.slice(4, -4);
  versions.push({ version, name });
  chunks.push(`-- Source migration: ${fileName}\n${removeMigrationBookkeeping(await readFile(join(migrationsDirectory, fileName), "utf8"))}`);
}

const bookkeeping = versions
  .map(({ version, name }) => `  (${version}, '${name.replaceAll("'", "''")}')`)
  .join(",\n");
const output = `-- OCRCraft database baseline v1.0\n-- Generated by: npm run db:build-initial\n-- Source: src/server/db/migrations/*.sql\n-- Do not edit manually; update a numbered migration and regenerate.\n\nBEGIN TRANSACTION;\n\n${chunks.join("\n\n")}\n\nINSERT INTO schema_migrations (version, name) VALUES\n${bookkeeping};\n\nCOMMIT;\n`;

await writeFile(outputPath, output, "utf8");
console.log(`Wrote ${outputPath} from ${fileNames.length} migrations.`);
